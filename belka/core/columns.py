"""
belka.core.columns — то, что ОБЯЗАНО быть одинаковым во всех шаблонах, чем
бы они ни генерировались.

09.2026, по итогам ревью: список системных колонок был скопирован в двух
генераторах (`generate.py` у Базара и `psb_generate.py` у ПСБ-складов), и
копии разошлись — у ПСБ-складов не оказалось четырёх B2B-колонок (ТН ВЭД,
Кратность заказа, Минимальное количество, Количество в упаковке), а
разделитель дополнительных изображений у одного был ", ", у другого ";".
Теперь общее живёт здесь, и оба генератора подмешивают один и тот же блок —
расхождение становится невозможным структурно, а не по дисциплине.

Здесь же:
  * normalize_attr_key — единое приведение имени атрибута/заголовка;
  * build_barcode — единое правило штрихкода (префикс склада + Id, ровно 13).
"""
from __future__ import annotations

import re
from typing import Any, Callable

from .text import casefold_ru
from .xlsx import clean_header

#: Разделитель списка дополнительных изображений. Значение проверено на
#: реальных загрузках Базара (431 строка), у ПСБ-складов было ";" — приведено
#: к общему.
IMAGES_SEPARATOR = ", "

#: Длина штрихкода, который пайплайн генерирует сам. Чужие штрихкоды из
#: источника под это правило НЕ подпадают (решение пользователя): обрезать
#: их значило бы менять идентификатор уже залитых товаров.
BARCODE_LENGTH = 13

_TRAILING_PAREN_RE = re.compile(r"\s*\([^)]*\)\s*$")


def normalize_attr_key(name) -> str:
    """'Бренд(Brend) * (справочник)' -> 'бренд'.

    Снимает по порядку: "*" и "(справочник)" (через общий clean_header —
    тот же код, которым import_check разбирает заголовки), затем скобочный
    суффикс транслитерации, который схема категорий Белки добавляет к
    display_name ("Бренд(Brend)"), а источник товаров — нет. Дальше
    casefold_ru (регистр + ё/е).

    Работает от любого конца: и от полного заголовка колонки, и от голого
    display_name, и от attributeName источника — поэтому одна функция
    годится и генераторам, и разбору готовых файлов."""
    base, _, _ = clean_header(name)
    if base is None:
        return ""
    return casefold_ru(_TRAILING_PAREN_RE.sub("", base))


def build_barcode(prefix: str, raw_id, length: int = BARCODE_LENGTH) -> str:
    """Штрихкод из префикса склада и Id товара, ровно `length` символов.

    Префикс задаётся на складе (WarehouseConfig.barcode_prefix). Цифры Id
    дополняются нулями слева до оставшейся длины; если цифр больше, берутся
    ПОСЛЕДНИЕ — так соседние Id остаются различимыми (отрезать начало у
    400457846/400457847 значило бы получить одинаковые штрихкоды).

    Проверено на реальных Id: 49440 -> 4700000049440, 400457846 ->
    4700400457846, 20086324 -> 4700020086324 — везде 13 символов."""
    digits = re.sub(r"\D", "", str(raw_id or ""))
    if not digits:
        return ""
    pad = length - len(prefix)
    if pad <= 0:
        raise ValueError(f"Префикс штрихкода '{prefix}' не короче требуемой длины {length}")
    tail = digits[-pad:] if len(digits) > pad else digits.zfill(pad)
    return f"{prefix}{tail}"


def b2b_direct_fields(
    tnved: Callable[[Any], Any],
    order_multiplicity: Callable[[Any], Any],
    min_order_quantity: Callable[[Any], Any],
    quantity_in_package: Callable[[Any], Any],
) -> list:
    """B2B-колонки — ОБЯЗАТЕЛЬНАЯ часть любого шаблона, на любом складе.

    Возвращает список (header, is_required, filler) в том же формате, что и
    остальные direct-поля генераторов (см. build_template_columns). Каждый
    генератор передаёт сюда свои извлекатели значений — у Базара они читают
    JSON-экспорт, у ПСБ-складов источника нет и передаётся `lambda p: None`,
    то есть значение придёт из заглушки (см. belka/core/defaults.py) и
    попадёт в отчёт перед подстановкой.

    Все четыре помечены обязательными И получают "*" в заголовке. Раньше у
    «Количество в упаковке» стоял is_required=True, но звёздочки в заголовке
    не было — из-за чего generate считал колонку обязательной, а import_check
    (он смотрит на "*" в заголовке) — нет."""
    return [
        ("ТН ВЭД *", True, tnved),
        ("Кратность заказа *", True, order_multiplicity),
        ("Минимальное количество *", True, min_order_quantity),
        ("Количество в упаковке *", True, quantity_in_package),
    ]
