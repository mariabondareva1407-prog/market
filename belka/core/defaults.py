#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
belka.core.defaults — ЕДИНЫЙ на весь проект реестр заглушек: чем пайплайн
заполняет обязательную колонку, если у источника данных для неё нет.

Зачем один реестр (09.2026, решение пользователя): раньше заглушки были
раскиданы по генераторам разными способами — `get_safe_value(..., 1)` в
одном месте, константа `DESCRIPTION_PLACEHOLDER_DEFAULT` в другом, `0` в
габаритах третьим, «да» в активности прямо в лямбде — и подставлялись
МОЛЧА, по одному товару. Теперь набор один, общий для всех складов и всех
шаблонов, а склад может переопределить отдельные ключи, не трогая
остальные:

    CONFIG = WarehouseConfig(..., placeholders={"description": "Нет данных"})

Значение `None` в переопределении означает «этому складу заглушку не
подставлять» — ячейка останется пустой, а пропуск попадёт в отчёт. Так
выборочное отключение делается тем же механизмом, без отдельных флагов.

Читается через PipelineContext.placeholder(key) / placeholders_report().

ВНЕ этого механизма (по решению пользователя) остаются дефолты из
attribute_mapping.json — это ручной, заранее заданный маппинг атрибутов
Bazar -> Белки, а не заглушка на отсутствующие данные. Их количество
всё равно попадает в итоговую сводку generate, чтобы не получалось, как
с брендом (412 ячеек из 432 молча заполнились значением «Без бренда»).
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any


@dataclass(frozen=True)
class Placeholder:
    """Одна заглушка.

    key      — стабильный идентификатор, он же ключ переопределения в рецепте;
    columns  — заголовки колонок (без "*"/"(справочник)"), к которым относится;
    value    — что подставляем; None = «значение вычисляется» (см. barcode);
    always   — True: это константа формата, а не запасной вариант на пустоту.
               Такие подставляются всегда и НЕ считаются пропуском данных
               (иначе «Активность товара на маркете = да» засоряла бы отчёт
               строкой на каждый товар), но остаются переопределяемыми.
    note     — человекочитаемое описание для отчёта перед подстановкой.
    """

    key: str
    columns: tuple[str, ...]
    value: Any
    note: str
    always: bool = False
    #: значение не константа, а вычисляется по строке (сейчас только штрихкод:
    #: префикс склада + Id товара). Переопределение в рецепте отменяет
    #: вычисление: значение из рецепта используется как есть, а None в
    #: переопределении означает «не подставлять вовсе».
    computed: bool = False


PLACEHOLDERS: dict[str, Placeholder] = {
    # --- B2B-колонки: добавляются во ВСЕ шаблоны всех складов (см.
    # belka/core/columns.py). У ПСБ-складов источника для них нет вообще,
    # поэтому там они целиком приходят отсюда.
    "tnved": Placeholder(
        "tnved", ("ТН ВЭД",), "8500000000",
        "код ТН ВЭД, когда его нет у источника",
    ),
    "order_multiplicity": Placeholder(
        "order_multiplicity", ("Кратность заказа",), 1,
        "кратность заказа, когда её нет у источника",
    ),
    "min_order_quantity": Placeholder(
        "min_order_quantity", ("Минимальное количество",), 1,
        "минимальное количество, когда его нет у источника",
    ),
    "quantity_in_package": Placeholder(
        "quantity_in_package", ("Количество в упаковке",), 1,
        "количество в упаковке, когда его нет у источника",
    ),
    # --- прочие обязательные поля
    "description": Placeholder(
        "description", ("Описание",), "нет описания",
        "описание, когда его нет ни у источника, ни в файле ассортимента",
    ),
    "vat": Placeholder(
        "vat", ("НДС",), "22%",
        "ставка НДС, когда код НДС неизвестен",
    ),
    "dimensions": Placeholder(
        "dimensions", ("Вес, Кг", "Ширина, см", "Высота, см", "Длина, см"), 0,
        "габариты и вес, когда их нет у источника",
    ),
    "barcode": Placeholder(
        "barcode", ("Штрихкод",), None,
        "штрихкод собирается из префикса склада и Id товара, ровно 13 символов "
        "(чужие штрихкоды из источника не трогаются)",
        computed=True,
    ),
    # --- константы формата: подставляются всегда, пропуском не считаются
    "activity": Placeholder(
        "activity", ("Активность товара на маркете",), "да",
        "активность товара на маркете", always=True,
    ),
}

#: колонка (без "*"/"(справочник)") -> ключ заглушки
COLUMN_TO_KEY: dict[str, str] = {
    column: ph.key for ph in PLACEHOLDERS.values() for column in ph.columns
}


def resolve(key: str, overrides: dict | None = None) -> Any:
    """Значение заглушки с учётом переопределения склада. None = не подставлять."""
    if key not in PLACEHOLDERS:
        raise KeyError(f"Неизвестная заглушка '{key}'. Известные: {sorted(PLACEHOLDERS)}")
    if overrides and key in overrides:
        return overrides[key]
    return PLACEHOLDERS[key].value


def is_overridden(key: str, overrides: dict | None = None) -> bool:
    return bool(overrides) and key in overrides
